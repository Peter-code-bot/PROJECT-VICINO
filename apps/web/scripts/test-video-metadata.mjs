import assert from 'node:assert/strict';
import { readFile, mkdtemp, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import ts from 'typescript';

const source = await readFile(new URL('../lib/media/video-metadata.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText
  .replace(/^import .*;\r?\n/gm, '').replace('export async function', 'async function');
const inspect = new Function('VIDEO_MAX_SECONDS', 'VIDEO_OUTPUT_MAX_BYTES', `${js}; return readProductVideoMetadata;`)(10, 10 * 1024 * 1024);
const box = (type, payload = Buffer.alloc(0)) => { const b = Buffer.alloc(8); b.writeUInt32BE(payload.length + 8); b.write(type, 4, 'latin1'); return Buffer.concat([b, payload]); };
const duration = Buffer.alloc(20); duration.writeUInt32BE(1000, 12); duration.writeUInt32BE(1000, 16);
const fake = Buffer.concat([box('ftyp', Buffer.from('isom0000')), box('mvhd', duration), box('avc1')]);
await assert.rejects(inspect(new Blob([fake]))); // previous 52-byte bypass
await assert.rejects(inspect(new Blob([Buffer.alloc(7)])));
await assert.rejects(inspect(new Blob([box('ftyp', Buffer.from('isom0000')), box('moof')])));

const root = fileURLToPath(new URL('../../..', import.meta.url));
const ffmpeg = process.env.MEDIA_FFMPEG ?? resolve(root, 'workers/product-media/.runtime/ffmpeg-9.0.2-essentials_build/bin/ffmpeg.exe');
if (!existsSync(ffmpeg)) throw new Error('Set MEDIA_FFMPEG to a real FFmpeg executable to run codec fixtures.');
const temporary = await mkdtemp(join(tmpdir(), 'vicino-mp4-'));
function generate(name, extra = []) {
  const path = join(temporary, name);
  const result = spawnSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=320x240:r=30',
    '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000', '-t', '1', '-c:v', 'libx264', '-pix_fmt', 'yuv420p',
    '-c:a', 'aac', '-map_metadata', '-1', '-movflags', '+faststart', ...extra, '-y', path], { encoding: 'utf8', timeout: 30000 });
  assert.equal(result.status, 0, result.error?.message ?? result.stderr); return path;
}
try {
  const real = await readFile(generate('valid.mp4'));
  const result = await inspect(new Blob([real], { type: 'video/mp4' }));
  assert.equal(result.duration, 1);
  const boundary = await readFile(generate('ten-seconds.mp4', ['-t', '10']));
  assert.equal((await inspect(new Blob([boundary]))).duration, 10);
  const silent = await readFile(generate('silent.mp4', ['-an']));
  assert.equal((await inspect(new Blob([silent]))).duration, 1);
  const sampleWords = Buffer.from(real), mdat = sampleWords.indexOf(Buffer.from('mdat'));
  sampleWords.write('GPS location EXIF', mdat + 4); // sample bytes are deliberately outside metadata admission
  assert.equal((await inspect(new Blob([sampleWords]))).duration, 1);
  let rejected = 0;
  const mutation = async (type, edit) => {
    const value = Buffer.from(real); const token = Buffer.from(type, 'latin1');
    const at = type === 'avc1' ? value.lastIndexOf(token) : value.indexOf(token);
    assert.ok(at > 3, `fixture lacks ${type}`); edit(value, at + 4);
    await assert.rejects(inspect(new Blob([value])), type); rejected++;
  };
  await mutation('mvhd', (b, at) => b.writeUInt32BE(500, at + 16));
  await mutation('mdhd', (b, at) => b.writeUInt32BE(999999, at + 16));
  await mutation('stsz', (b, at) => b.writeUInt32BE(9999, at + 8));
  await mutation('stts', (b, at) => b.writeUInt32BE(9999, at + 8));
  await mutation('stco', (b, at) => b.writeUInt32BE(0, at + 8));
  await mutation('avc1', (b, at) => b.write('hvc1', at - 4));
  await mutation('mp4a', (b, at) => b.write('Opus', at - 4));
  await mutation('avcC', (b, at) => b.writeUInt8(2, at));
  await mutation('tkhd', (b, at) => b.writeUInt32BE(4096 * 65536, at + 76));
  await mutation('tkhd', (b, at) => b.writeInt32BE(2 * 65536, at + 40));
  await mutation('url ', (b, at) => b.writeUInt32BE(0, at));
  // GPS metadata is rejected; ordinary encoder metadata generated by FFmpeg was accepted above.
  const located = await readFile(generate('location.mp4', ['-metadata', 'location=+19.4326-099.1332/']));
  await assert.rejects(inspect(new Blob([located])), /ubicación/);
  const fragmented = await readFile(generate('fragmented.mp4', ['-movflags', 'frag_keyframe+empty_moov']));
  await assert.rejects(inspect(new Blob([fragmented])));
  console.log(`video metadata: 4 real/container fixtures accepted; ${rejected + 5} adversarial/unsupported cases rejected`);
} finally { await rm(temporary, { recursive: true, force: true }); }
